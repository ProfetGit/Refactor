#!/usr/bin/env python3
"""Generate Data/ProfessionThresholds.lua from Blizzard's SkillLineAbility table.

Every crafting recipe carries the skill level where it turns yellow (TrivialSkillLineRankLow) and
where it turns grey (TrivialSkillLineRankHigh). The client hands addons neither number, so the
module reads them from here. wago.tools publishes the table as CSV per build:

    python3 -I Tools/profession-thresholds.py --build 1.60.1.70009 --download

or from a CSV already on disk (SkillLineAbility.csv):

    python3 -I Tools/profession-thresholds.py --build 1.60.1.70009 --source DIR
"""
import argparse
import csv
import datetime
import sys
import textwrap
import urllib.request
from pathlib import Path

TABLE = "SkillLineAbility"
OUTPUT = Path("Data/ProfessionThresholds.lua")
CHUNK_INDENT = " " * 12
MAX_LINE = 120
MAX_CHUNK = MAX_LINE - len(CHUNK_INDENT) - 3


def fetch(build, target):
    url = f"https://wago.tools/db2/{TABLE}/csv?build={build}"
    request = urllib.request.Request(url, headers={"User-Agent": "Refactor profession-thresholds"})
    with urllib.request.urlopen(request) as response:
        text = response.read().decode("utf-8")
    if not text.startswith("ID,") and "ID" not in text.split("\n", 1)[0]:
        raise SystemExit(f"{url} did not return a CSV table")
    target.write_text(text, encoding="utf-8")
    print(f"fetched {TABLE}: {len(text)} bytes")


def chunk(entries):
    chunks, current = [], ""
    for entry in entries:
        joined = f"{current};{entry}" if current else entry
        if len(joined) > MAX_CHUNK and current:
            chunks.append(current)
            current = entry
        else:
            current = joined
    if current:
        chunks.append(current)
    return chunks


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", required=True, help="client build, for example 1.60.1.70009")
    parser.add_argument("--source", help="directory holding SkillLineAbility.csv")
    parser.add_argument("--download", action="store_true", help="fetch the CSV from wago.tools into --source")
    args = parser.parse_args()

    source = Path(args.source) if args.source else Path(".tools/profession-thresholds") / args.build
    path = source / f"{TABLE}.csv"
    if args.download:
        source.mkdir(parents=True, exist_ok=True)
        fetch(args.build, path)
    if not path.exists():
        raise SystemExit(f"missing {path}; pass --download or --source")

    groups = {}
    skipped = inverted = duplicates = conflicts = 0
    with path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            spell, high = int(row["Spell"]), int(row["TrivialSkillLineRankHigh"])
            if spell <= 0 or high <= 0:
                skipped += 1
                continue
            low = int(row["TrivialSkillLineRankLow"])
            if low > high:
                inverted += 1
                continue
            rowID = int(row["ID"])
            bySpell = groups.setdefault(int(row["SkillLine"]), {})
            seen = bySpell.get(spell)
            if seen is None:
                bySpell[spell] = (rowID, low, high)
            elif seen[1:] == (low, high):
                duplicates += 1
            else:
                conflicts += 1
                if rowID < seen[0]:
                    bySpell[spell] = (rowID, low, high)

    count = sum(len(bySpell) for bySpell in groups.values())
    summary = (f"{count} recipes on {len(groups)} skill lines; left out: {skipped} without a spell or "
               f"grey level, {inverted} with low above high; merged {duplicates} identical duplicates; "
               f"{conflicts} conflicting duplicates resolved to the lowest row ID.")
    lines = [
        "-- Generated by Tools/profession-thresholds.py. Do not edit by hand.",
        f"-- Source: wago.tools {TABLE} for build {args.build}, read {datetime.date.today().isoformat()}. Per profession",
        '-- skill line, every recipe (spell ID) as "spell,low,high" joined by ";": yellow from low, green',
        "-- from halfway between, grey from high. Static data for that build; the module checks each",
        "-- recipe against the live client and falls back to observation where they disagree.",
    ]
    lines += ["-- " + part for part in textwrap.wrap(summary, MAX_LINE - 3)]
    lines += [
        "local _, R = ...",
        "R.ProfessionThresholds = {",
        f'    build = "{args.build}",',
        "    lines = {",
    ]
    for line in sorted(groups):
        entries = [f"{spell},{low},{high}" for spell, (_, low, high) in sorted(groups[line].items())]
        lines.append(f"        [{line}] = {{")
        for text in chunk(entries):
            lines.append(f'{CHUNK_INDENT}"{text}",')
        lines.append("        },")
    lines += ["    },", "}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT}: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
