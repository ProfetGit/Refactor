#!/usr/bin/env python3
"""Generate Data/DungeonEntrances.lua from the client's own Map, UiMap and UiMapAssignment tables.

Forever's C_EncounterJournal.GetDungeonEntrancesForMap returns nothing (no Encounter Journal),
so the entrances come from the tables. Map lists every instance with the world position of its
door (Corpse_0/Corpse_1, where a ghost is released) on its CorpseMapID, and UiMapAssignment
says which world rectangle each world map shows, which turns that position into a spot on the
map. wago.tools publishes both as CSV per build:

    python3 Tools/dungeon-entrances.py --build 1.60.1.70790 --interface 16001 --download

or from CSVs already on disk (Map.csv, UiMap.csv, UiMapAssignment.csv):

    python3 Tools/dungeon-entrances.py --build 1.60.1.70790 --interface 16001 --source DIR
"""
import argparse
import csv
import datetime
import urllib.request
from pathlib import Path

TABLES = ["Map", "UiMap", "UiMapAssignment"]
OUTPUT = Path("Data/DungeonEntrances.lua")
# Door positions closer than this on one map (a share of the map) share one pin: Blackrock
# Mountain holds four instances in one spot.
MERGE = 0.02
SKIP_NAMES = ("<unused>", "Test", "Scott", "Collin", "CashTest")


def fetch(table, build, target):
    url = f"https://wago.tools/db2/{table}/csv?build={build}"
    request = urllib.request.Request(url, headers={"User-Agent": "Refactor dungeon-entrances"})
    with urllib.request.urlopen(request) as response:
        text = response.read().decode("utf-8")
    if "ID" not in text.split("\n", 1)[0]:
        raise SystemExit(f"{url} did not return a CSV table")
    target.write_text(text)
    print(f"fetched {table}: {len(text)} bytes")


def read(path):
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", required=True)
    parser.add_argument("--interface", required=True, type=int)
    parser.add_argument("--source", help="directory holding the CSVs")
    parser.add_argument("--download", action="store_true")
    args = parser.parse_args()
    source = Path(args.source) if args.source else Path(".tools/dungeon-entrances") / args.build
    if args.download:
        source.mkdir(parents=True, exist_ok=True)
        for table in TABLES:
            fetch(table, args.build, source / f"{table}.csv")
    maps = {row["ID"]: row for row in read(source / "UiMap.csv")}
    assignments = read(source / "UiMapAssignment.csv")

    doors = []
    for row in read(source / "Map.csv"):
        name = row["MapName_lang"]
        if row["InstanceType"] not in ("1", "2") or row["CorpseMapID"] not in ("0", "1"):
            continue
        if name.startswith(SKIP_NAMES) or (float(row["Corpse_0"]) == 0 and float(row["Corpse_1"]) == 0):
            continue
        doors.append((name, row["CorpseMapID"], float(row["Corpse_0"]), float(row["Corpse_1"]),
                      row["InstanceType"] == "2"))

    placed = {}
    for name, continent, wx, wy, raid in doors:
        # World x runs north and world y runs west; a map's x runs east and its y south.
        found = []
        for a in assignments:
            ui = maps.get(a["UiMapID"])
            if a["MapID"] != continent or not ui or ui["System"] != "0" or ui["Type"] not in ("2", "3"):
                continue
            x0, y0, x1, y1 = (float(a[k]) for k in ("Region_0", "Region_1", "Region_3", "Region_4"))
            if x0 <= wx <= x1 and y0 <= wy <= y1:
                found.append((int(a["UiMapID"]), (y1 - wy) / (y1 - y0), (x1 - wx) / (x1 - x0), ui["Type"]))
        # Zone rectangles overlap, so a door is drawn on the continent and on the one zone it
        # is nearest the middle of, not on every zone whose rectangle happens to contain it.
        zones = [f for f in found if f[3] == "3"]
        keep = [f for f in found if f[3] == "2"]
        if zones:
            keep.append(min(zones, key=lambda f: (f[1] - 0.5) ** 2 + (f[2] - 0.5) ** 2))
        for ui_id, x, y, _ in keep:
            placed.setdefault(ui_id, []).append((x, y, name, raid))

    out = [
        "-- Generated by Tools/dungeon-entrances.py. Do not edit by hand.",
        f"-- Source: wago.tools Map, UiMap and UiMapAssignment for build {args.build}, read",
        f"-- {datetime.date.today().isoformat()}. Where each dungeon and raid is entered, by UI map ID, as x and y",
        "-- on that map. The position is the instance's release point, the nearest the tables get to",
        "-- the door. Static data, never invalidated.",
        "local _, R = ...",
        "R.DungeonEntrances = {",
        f"    interface = {args.interface},",
        f'    build = "{args.build}",',
        "    maps = {",
    ]
    for ui_id in sorted(placed):
        groups = []
        for x, y, name, raid in sorted(placed[ui_id], key=lambda p: (p[2])):
            for group in groups:
                if abs(group["x"] - x) <= MERGE and abs(group["y"] - y) <= MERGE:
                    group["names"].append(name)
                    group["raid"] = group["raid"] and raid
                    break
            else:
                groups.append({"x": x, "y": y, "names": [name], "raid": raid})
        out.append(f"        [{ui_id}] = {{ -- {maps[str(ui_id)]['Name_lang']}")
        for group in groups:
            names = ", ".join(lua_string(n) for n in group["names"])
            out.append(f"            {{ x = {group['x']:.4f}, y = {group['y']:.4f}, raid = {str(group['raid']).lower()}, "
                       f"names = {{ {names} }} }},")
        out.append("        },")
    out += ["    },", "}", ""]
    OUTPUT.write_text("\n".join(out))
    print(f"wrote {OUTPUT}: {sum(len(v) for v in placed.values())} placements on {len(placed)} maps")


if __name__ == "__main__":
    main()
