"""Writes metrics.lua: per-character advances of the font the preview renders text in.

The preview measures text in Lua (GetStringWidth) and draws it in a browser; both have to
agree, so both use DejaVu Serif Condensed, the closest installed stand-in for Friz Quadrata.
Run: python3 Tools/Preview/metrics.py
"""
import os
from PIL import ImageFont

FONT = "/usr/share/fonts/TTF/DejaVuSerifCondensed.ttf"
SIZE = 1000
font = ImageFont.truetype(FONT, SIZE)
lines = ["-- Generated by Tools/Preview/metrics.py: advance per character at size 1, DejaVu Serif Condensed.",
         "return {"]
for code in range(32, 127):
    advance = font.getlength(chr(code)) / SIZE
    lines.append("    [%d] = %.4f," % (code, advance))
lines.append("}")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "metrics.lua")
with open(out, "w") as handle:
    handle.write("\n".join(lines) + "\n")
print("wrote", out)
