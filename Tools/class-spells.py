#!/usr/bin/env python3
"""Generate Data/ClassSpells.lua: the spells each class learns, with the level it learns them.

No client call lists the spells a character has not learned yet; the class trainer's window is the
only live source, and interface.allSpells records it on a visit. This is the same answer taken from
the client's own tables, which wago.tools publishes as CSV per build:

    python3 Tools/class-spells.py --build 1.60.1.70888 --interface 16001 --download

or from CSVs already on disk (SkillLineAbility, SpellLevels, SkillLine, Talent, ChrClasses):

    python3 Tools/class-spells.py --build 1.60.1.70888 --interface 16001 --source DIR

There is no trainer table in the published data, so the list is a close fit rather than the trainer's
own: a class skill line's spells that carry a level and are not talents. Against a recorded mage
trainer list, 156 of 161 spells are found with the same level, and the remainder is held back by
the filters below. A recorded trainer list always wins over this file at runtime.
"""
import argparse
import csv
import datetime
import re
import sys
import urllib.request
from pathlib import Path

TABLES = ["SkillLineAbility", "SpellLevels", "SkillLine", "Talent", "ChrClasses", "SpellName"]
OUTPUT = Path("Data/ClassSpells.lua")
CLASS_CATEGORY = "7"
# Class skill lines that are not the player's own spellbook: pets, mounts, companions and the
# season-of-discovery rune lines, which are learned by engraving, not by level.
NOT_PLAYER = re.compile(r"^(Pet - |Beast Training|Mounts|Companions|Engraving|Runes|Meditation|Explorer)")
# Teleports and portals are taught per faction; the trainer only offers the player's own cities.
FACTION_CITY = {
    "Stormwind": "Alliance", "Ironforge": "Alliance", "Darnassus": "Alliance", "Exodar": "Alliance",
    "Orgrimmar": "Horde", "Undercity": "Horde", "Thunder Bluff": "Horde", "Silvermoon": "Horde",
}
TRAVEL = re.compile(r"^(Teleport|Portal): (.+)$")


def fetch(table, build, target):
    url = f"https://wago.tools/db2/{table}/csv?build={build}"
    request = urllib.request.Request(url, headers={"User-Agent": "Refactor class-spells"})
    with urllib.request.urlopen(request) as response:
        text = response.read().decode("utf-8")
    if "ID" not in text.split("\n", 1)[0]:
        raise SystemExit(f"{url} did not return a CSV table")
    target.write_text(text)
    print(f"fetched {table}: {len(text)} bytes")


def rows(directory, table):
    with open(directory / f"{table}.csv", newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def build_tables(directory):
    classes = {1 << (int(r["ID"]) - 1): r["Filename"] for r in rows(directory, "ChrClasses")}
    skill_lines = {r["ID"]: r for r in rows(directory, "SkillLine")}
    names = {int(r["ID"]): r["Name_lang"] for r in rows(directory, "SpellName")}
    levels = {}
    for r in rows(directory, "SpellLevels"):
        if r["DifficultyID"] == "0":
            levels[int(r["SpellID"])] = int(r["BaseLevel"])
    talents = set()
    for r in rows(directory, "Talent"):
        for key, value in r.items():
            if key.startswith("SpellRank_") and value not in ("", "0"):
                talents.add(int(value))
    spells = {name: {} for name in classes.values()}
    lines = {name: {} for name in classes.values()}
    faction = {}
    for r in rows(directory, "SkillLineAbility"):
        line = skill_lines.get(r["SkillLine"])
        if not line or line["CategoryID"] != CLASS_CATEGORY or NOT_PLAYER.match(line["DisplayName_lang"]):
            continue
        if r["AcquireMethod"] != "0":
            continue
        spell = int(r["Spell"])
        level = levels.get(spell, 0)
        name = names.get(spell)
        if level <= 0 or not name or spell in talents:
            continue
        travel = TRAVEL.match(name)
        if travel and travel.group(2) not in FACTION_CITY:
            continue
        mask = int(r["ClassMask"])
        for bit, class_file in classes.items():
            if mask & bit:
                spells[class_file][spell] = level
                lines[class_file][spell] = line["DisplayName_lang"]
                if travel:
                    faction[spell] = FACTION_CITY[travel.group(2)]
    return spells, lines, faction


def write(spells, lines, faction, build, interface):
    out = [
        "-- Generated by Tools/class-spells.py. Do not edit by hand.",
        f"-- Source: wago.tools SkillLineAbility, SpellLevels, SkillLine, Talent, ChrClasses and SpellName for",
        f"-- build {build}, read {datetime.date.today().isoformat()}. The spells each class learns, by spell id,",
        "-- with the level that teaches them. A close fit to the trainer lists, not the trainer's own; see the",
        "-- script. Static data, never invalidated.",
        "local _, R = ...",
        "R.ClassSpells = {",
        f"    interface = {interface},",
        f'    build = "{build}",',
        "    spells = {",
    ]
    for class_file in sorted(spells):
        if not spells[class_file]:
            continue
        out.append(f"        {class_file} = {{")
        entries = sorted(spells[class_file].items(), key=lambda item: (item[1], item[0]))
        line = "           "
        for spell, level in entries:
            piece = f" [{spell}] = {level},"
            if len(line) + len(piece) > 108:
                out.append(line)
                line = "           "
            line += piece
        out.append(line)
        out.append("        },")
    out.append("    },")
    out.append("    lines = {")
    for class_file in sorted(lines):
        if not lines[class_file]:
            continue
        out.append(f"        {class_file} = {{")
        row = "           "
        for spell, name in sorted(lines[class_file].items()):
            piece = f' [{spell}] = "{name}",'
            if len(row) + len(piece) > 108:
                out.append(row)
                row = "           "
            row += piece
        out.append(row)
        out.append("        },")
    out.append("    },")
    out.append("    faction = {")
    for spell in sorted(faction):
        out.append(f'        [{spell}] = "{faction[spell]}",')
    out.append("    },")
    out.append("}")
    OUTPUT.write_text("\n".join(out) + "\n")
    total = sum(len(v) for v in spells.values())
    print(f"wrote {OUTPUT}: {total} spells across {sum(1 for v in spells.values() if v)} classes")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", required=True)
    parser.add_argument("--interface", required=True, type=int)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--download", action="store_true")
    args = parser.parse_args()
    directory = args.source or Path(".tools/class-spells-csv")
    if args.download:
        directory.mkdir(parents=True, exist_ok=True)
        for table in TABLES:
            fetch(table, args.build, directory / f"{table}.csv")
    elif not directory.is_dir():
        sys.exit("pass --download, or --source with the CSV tables")
    spells, lines, faction = build_tables(directory)
    write(spells, lines, faction, args.build, args.interface)


if __name__ == "__main__":
    main()
